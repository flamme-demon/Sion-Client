export function deviceOperatingSystem(
  userAgent = navigator.userAgent,
  maxTouchPoints = navigator.maxTouchPoints,
): string {
  if (/Android/i.test(userAgent)) return "Android";
  if (/iPhone|iPad|iPod/i.test(userAgent) || (/Macintosh/i.test(userAgent) && maxTouchPoints > 1)) return "iOS";
  if (/Windows/i.test(userAgent)) return "Windows";
  if (/Macintosh|Mac OS X/i.test(userAgent)) return "macOS";
  if (/Linux/i.test(userAgent)) return "Linux";
  return "Unknown";
}

export function deviceDisplayName(version: string): string {
  const os = deviceOperatingSystem();
  const kind = os === "Android" || os === "iOS" ? "Mobile" : "Desktop";
  return `Sion Client ${version} — ${kind} (${os})`;
}

/** Only migrate labels generated by Sion; personal device names stay intact. */
export function isAutomaticDeviceName(name: string | null | undefined): boolean {
  if (!name || name === "Sion Android" || name === "Sion (moteur Rust)") return true;
  return /^Sion Client \d+\.\d+\.\d+(?:[-+][\w.+-]+)?(?: — (?:Desktop|Mobile))? \((?:Windows|macOS|Linux|Android|iOS|Unknown)\)(?: — moteur Rust)?$/.test(name);
}
